-- =====================================================================
-- 予約台帳 (yoyaku-daicho) の DB を勤怠システムのプロジェクトに統合 (2026-10-13)
--
-- 元: Supabase プロジェクト rlzltklfclzakcmpctga (予約台帳専用) → 本プロジェクト yczwdkkuaitlbvtskmsf
-- 台帳のテーブルは本プロジェクトの stores と名前が衝突するため、すべて yoyaku_ 接頭辞を付ける。
--   stores → yoyaku_stores / reservations → yoyaku_reservations / events → yoyaku_events
--   store_members → yoyaku_store_members / ai_usage → yoyaku_ai_usage
--   google_cache → yoyaku_google_cache / google_usage → yoyaku_google_usage
-- RPC 関数名 (booking_* / ai_join_store / booking_track) は台帳アプリがそのまま呼ぶので変えない。
-- アクセス制御は台帳の設計どおり: スタッフ (Supabase Auth でログイン) = authenticated ロールのポリシー、
-- お客様 (匿名) = security definer の booking_* 関数経由のみ。勤怠側のテーブルにはポリシーが無いので
-- ログイン済みスタッフからも読めない (従来どおり Edge Function "api" 経由のみ)。
-- 店舗の対応は stores."reservationStoreId" (勤怠側 stores) で持つ。
-- =====================================================================

-- ---------- テーブル ----------
create table if not exists public.yoyaku_stores (
  id          text primary key,
  name        text not null default '',
  doc         jsonb not null default '{}'::jsonb,
  updated_at  timestamptz not null default now()
);

create table if not exists public.yoyaku_reservations (
  id            text primary key,
  store_id      text not null references public.yoyaku_stores(id) on delete cascade,
  date          text not null,                 -- 'YYYY-MM-DD'
  start_min     integer not null default 0,    -- 開始（分）
  duration      integer not null default 120,  -- 滞在（分）
  status        text not null default 'reserved',  -- reserved / seated / finished / cancelled / noshow
  table_ids     text[] not null default '{}',
  code          text,                          -- 予約番号（ネット予約）
  phone_digits  text,                          -- 電話番号（数字のみ、照合用）
  data          jsonb not null,                -- 予約オブジェクト全体（アプリと同じ形）
  updated_at    timestamptz not null default now()
);
create index if not exists yoyaku_reservations_store_date on public.yoyaku_reservations (store_id, date);
create index if not exists yoyaku_reservations_lookup on public.yoyaku_reservations (store_id, phone_digits, code);

create table if not exists public.yoyaku_events (
  id        bigint generated by default as identity primary key,
  store_id  text not null references public.yoyaku_stores(id) on delete cascade,
  t         timestamptz not null default now(),
  type      text not null,
  site      text,
  ref       text,
  dev       text,
  utm       text
);
create index if not exists yoyaku_events_store_t on public.yoyaku_events (store_id, t);

create table if not exists public.yoyaku_store_members (
  store_id    text not null references public.yoyaku_stores(id) on delete cascade,
  user_id     uuid not null,
  email       text not null default '',
  ai_allowed  boolean not null default false,
  created_at  timestamptz not null default now(),
  primary key (store_id, user_id)
);

create table if not exists public.yoyaku_ai_usage (
  id             bigint generated by default as identity primary key,
  store_id       text not null,
  user_id        uuid not null,
  purpose        text not null,
  model          text,
  input_tokens   integer not null default 0,
  output_tokens  integer not null default 0,
  created_at     timestamptz not null default now()
);
create index if not exists yoyaku_ai_usage_store_t on public.yoyaku_ai_usage (store_id, created_at);
create index if not exists yoyaku_ai_usage_user_t on public.yoyaku_ai_usage (user_id, created_at);

create table if not exists public.yoyaku_google_cache (
  key   text primary key,
  data  jsonb not null,
  at    timestamptz not null default now()
);

create table if not exists public.yoyaku_google_usage (
  id          bigint generated by default as identity primary key,
  bucket      text not null,
  op          text not null,
  created_at  timestamptz not null default now()
);
create index if not exists yoyaku_google_usage_bucket_t on public.yoyaku_google_usage (bucket, op, created_at);


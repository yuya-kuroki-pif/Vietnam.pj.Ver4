-- 店舗を作ったスタッフを自動でメンバー登録 (AI 利用可)
create or replace function public.store_creator_member() returns trigger
language plpgsql security definer set search_path = public as $$
declare v_email text;
begin
  if auth.uid() is null then return new; end if;
  select email into v_email from auth.users where id = auth.uid();
  insert into public.yoyaku_store_members (store_id, user_id, email, ai_allowed)
  values (new.id, auth.uid(), coalesce(v_email, ''), true)
  on conflict (store_id, user_id) do nothing;
  return new;
end $$;
drop trigger if exists yoyaku_stores_creator_member on public.yoyaku_stores;
create trigger yoyaku_stores_creator_member after insert on public.yoyaku_stores for each row execute function public.store_creator_member();

